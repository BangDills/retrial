const hre = require("hardhat");
const { ethers } = hre;
const fs = require("fs");
const path = require("path");

async function main() {
  const [deployer] = await ethers.getSigners();
  console.log(`Deploying contracts with account: ${deployer.address}`);

  const maxSupply = 3000;
  console.log(`Deploying RetrialNFT(maxSupply = ${maxSupply})...`);
  const NFTFactory = await ethers.getContractFactory("RetrialNFT");
  const nft = await NFTFactory.deploy(maxSupply);
  await nft.waitForDeployment();
  const nftAddress = await nft.getAddress();
  const nftTx = nft.deploymentTransaction()?.hash || "";
  console.log(`RetrialNFT deployed at: ${nftAddress}`);

  console.log(`Deploying RetrialMarket(nft = ${nftAddress})...`);
  const MarketFactory = await ethers.getContractFactory("RetrialMarket");
  const market = await MarketFactory.deploy(nftAddress);
  await market.waitForDeployment();
  const marketAddress = await market.getAddress();
  const marketTx = market.deploymentTransaction()?.hash || "";
  console.log(`RetrialMarket deployed at: ${marketAddress}`);

  // Set the shipped difficulty. The contract default is 20 bits, which costs a
  // phone ~1M keccak hashes (~2-4 minutes). Measured browser hashrate is ~26k
  // H/s on desktop, so 16 bits (~65k hashes, ~2-5s) is the usable default.
  // Raise it with DIFFICULTY_BITS=<8..32>, or nft.setDifficultyBits() later.
  const difficultyBits = Number(process.env.DIFFICULTY_BITS || 16);
  const diffTx = await nft.setDifficultyBits(difficultyBits);
  await diffTx.wait();
  console.log(
    `Challenge difficulty set to ${difficultyBits} bits (tx ${diffTx.hash})`
  );

  console.log("\n--- Deployment Table ---");
  console.table([
    { Contract: "RetrialNFT", Address: nftAddress, TxHash: nftTx },
    { Contract: "RetrialMarket", Address: marketAddress, TxHash: marketTx },
  ]);

  const networkInfo = await ethers.provider.getNetwork();
  const chainId = Number(networkInfo.chainId);

  let chainName = "Localhost";
  let rpcUrl = "http://127.0.0.1:8545";
  let explorer = "";

  if (chainId === 56) {
    chainName = "BNB Smart Chain";
    rpcUrl = process.env.BSC_RPC_URL || "https://bsc-dataseed.binance.org";
    explorer = "https://bscscan.com";
  } else if (chainId === 97) {
    chainName = "BNB Smart Chain Testnet";
    rpcUrl = process.env.BSC_TESTNET_RPC_URL || "https://data-seed-prebsc-1-s1.bnbchain.org:8545";
    explorer = "https://testnet.bscscan.com";
  } else if (chainId === 31337) {
    chainName = "Hardhat Local";
    rpcUrl = "http://127.0.0.1:8545";
    explorer = "";
  }

  const config = {
    chainId,
    chainName,
    rpcUrl,
    nftAddress,
    marketAddress,
    explorer,
  };

  const webDir = path.join(__dirname, "..", "web");
  if (!fs.existsSync(webDir)) {
    fs.mkdirSync(webDir, { recursive: true });
  }

  const configPath = path.join(webDir, "config.js");
  const configContent = `// Generated by scripts/deploy.js\nwindow.RETRIAL_CONFIG = ${JSON.stringify(config, null, 2)};\n`;
  fs.writeFileSync(configPath, configContent);
  console.log(`Successfully wrote configuration to ${configPath}`);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
